/**
 * 56-05 (D-09..D-12 / PAPER-01 / PAPER-04): the shared-panel Paper section.
 *
 * Trigger shows `Paper` + the current paper name. Clicking opens a thumbnail
 * grid popover: 3 columns, 64×64 cells, groups Procedural then Real (D-12 one
 * library, never tabs). Strength + scale SliderStepper rows sit directly under
 * the trigger, always reachable (D-10 / D-06).
 *
 * Cells show the RAW paper tile only (D-11) — the ported playground sheet
 * for procedural papers, the shipped jpg for real scans. No engine
 * involvement in the picker (the composite seam is paperPass; this is
 * presentation only).
 */
import type { JSX } from 'preact';
import {
  PAPER_LIBRARY,
  PAPER_UNITS,
  presetForPaperId,
  renderPaperSheet,
  type PaperDefinition,
} from '@efxlab/efx-watercolor/papers';
import { SliderStepper } from '../../shared/SliderStepper';

export interface PaperPickerProps {
  paperId: string;
  strength: number;
  scale: number;
  onPaperIdChange: (id: string) => void;
  onStrengthChange: (value: number) => void;
  onScaleChange: (value: number) => void;
  disabled?: boolean;
}

function paperName(paperId: string): string {
  return PAPER_LIBRARY.find((entry) => entry.id === paperId)?.name ?? paperId;
}

/** Cell size locked by UI-SPEC: 64×64 tiles, 8px grid gap. */
const CELL_SIZE = 64;
const GRID_GAP = 8;

/**
 * Ported playground sheet preview (D-11): the same paperColour sheet the
 * editor fond shows, generated by playgroundPaperField. Pure presentation —
 * no paperPass, no engine. Cached as ImageData per (id, size) so re-renders
 * never regenerate. Painted into a cell <canvas> — never a toDataURL string
 * (52.1 D-19 forbids the frame-transport base64 surface, including picker
 * thumbs). Thumb scale: a ~256-paper-unit-tall window of the sheet so the
 * grain reads at a glance the way the playground preview does.
 */
const reliefCache = new Map<string, ImageData | null>();
const THUMB_WINDOW_UNITS = 256;
function proceduralReliefImage(id: string): ImageData | null {
  const key = `${id}:${CELL_SIZE}`;
  const cached = reliefCache.get(key);
  if (cached !== undefined) return cached;
  if (typeof document === 'undefined') {
    reliefCache.set(key, null);
    return null;
  }
  const preset = presetForPaperId(id);
  if (!preset) {
    reliefCache.set(key, null);
    return null;
  }
  const canvas = document.createElement('canvas');
  canvas.width = CELL_SIZE;
  canvas.height = CELL_SIZE;
  const ctx = canvas.getContext('2d');
  if (!ctx) {
    reliefCache.set(key, null);
    return null;
  }
  const rgba = renderPaperSheet(CELL_SIZE, CELL_SIZE, PAPER_UNITS / THUMB_WINDOW_UNITS, 1, preset);
  const image = ctx.createImageData(CELL_SIZE, CELL_SIZE);
  image.data.set(rgba);
  reliefCache.set(key, image);
  return image;
}

/**
 * 261017-mdr: pre-fill the procedural thumb cache so the picker opens without
 * a first-open generation stall. Same renderPaperSheet + PAPER_UNITS /
 * THUMB_WINDOW_UNITS path proceduralReliefImage already uses — repeat calls
 * are reliefCache hits. Does not touch CELL_SIZE / GRID_GAP / the 3-column grid.
 */
export function warmProceduralReliefThumbs(): void {
  for (const entry of PAPER_LIBRARY) {
    if (entry.group !== 'procedural') continue;
    proceduralReliefImage(entry.id);
  }
}

function PaperCell(props: {
  entry: PaperDefinition;
  active: boolean;
  onSelect: (id: string) => void;
  disabled?: boolean;
}): JSX.Element {
  const isReal = props.entry.group === 'real';
  const relief = isReal ? null : proceduralReliefImage(props.entry.id);
  // Loading / decode-failure share one placeholder: --color-bg-input + name
  // (UI-SPEC loading + error rows — never a blank cell, never a crash).
  const showPlaceholder = isReal || relief === null;
  return (
    <button
      type="button"
      class={`paper-picker-cell${props.active ? ' active' : ''}`}
      data-paper-id={props.entry.id}
      data-paper-group={props.entry.group}
      aria-pressed={props.active}
      title={props.entry.name}
      disabled={props.disabled}
      onClick={() => props.onSelect(props.entry.id)}
      style={{
        width: `${CELL_SIZE}px`,
        height: `${CELL_SIZE}px`,
        padding: 0,
        border: props.active ? '2px solid var(--color-accent)' : '1px solid var(--color-border-subtle)',
        borderRadius: '6px',
        overflow: 'hidden',
        cursor: props.disabled ? 'default' : 'pointer',
        background: 'var(--color-bg-input)',
        position: 'relative',
      }}
    >
      {showPlaceholder ? (
        isReal ? (
          <img
            src={props.entry.source}
            alt={props.entry.name}
            data-paper-tile="real"
            style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }}
            onError={(event) => {
              // Decode failure keeps the placeholder fill + name (UI-SPEC
              // error row) — hide the broken image, never a blank crash.
              (event.currentTarget as HTMLImageElement).style.display = 'none';
            }}
          />
        ) : null
      ) : (
        <canvas
          data-paper-tile="procedural"
          aria-label={props.entry.name}
          width={CELL_SIZE}
          height={CELL_SIZE}
          ref={(el: HTMLCanvasElement | null) => {
            if (!el) return;
            const ctx = el.getContext('2d');
            if (ctx && relief) ctx.putImageData(relief, 0, 0);
          }}
          style={{ width: '100%', height: '100%', display: 'block' }}
        />
      )}
      <span
        class="paper-picker-cell-name"
        style={{
          position: 'absolute',
          inset: 0,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          fontSize: '10px',
          fontWeight: 600,
          textAlign: 'center',
          padding: '2px',
          pointerEvents: 'none',
          // The name stays visible on the placeholder; over a decoded tile it
          // sits as a quiet caption strip so the raw tile still reads.
          background: showPlaceholder ? 'transparent' : 'linear-gradient(transparent 55%, rgba(0,0,0,0.45))',
          color: showPlaceholder ? 'var(--color-text-secondary)' : '#fff',
        }}
      >
        {props.entry.name}
      </span>
    </button>
  );
}

export function PaperPicker(props: PaperPickerProps): JSX.Element {
  const procedural = PAPER_LIBRARY.filter((entry) => entry.group === 'procedural');
  const real = PAPER_LIBRARY.filter((entry) => entry.group === 'real');

  return (
    <div class="paper-picker" data-paper-picker style={{ display: 'flex', flexDirection: 'column', gap: '8px' }}>
      <div
        class="paper-picker-popover"
        data-paper-picker-popover
        style={{
          width: '100%',
          maxHeight: '320px',
          overflowY: 'auto',
          background: 'var(--color-bg-toolbar)',
          border: '1px solid var(--color-border-subtle)',
          borderRadius: '8px',
          padding: '12px',
          display: 'flex',
          flexDirection: 'column',
          gap: '8px',
        }}
      >
          <div
            class="paper-picker-group-header"
            data-paper-group-header="procedural"
            style={{
              position: 'sticky',
              top: 0,
              zIndex: 1,
              background: 'var(--color-bg-toolbar)',
              fontSize: '13px',
              fontWeight: 600,
              lineHeight: 1.2,
              color: 'var(--color-text-primary)',
              padding: '4px 0',
            }}
          >
            Procedural
          </div>
          <div
            class="paper-picker-grid"
            data-paper-group-grid="procedural"
            style={{
              display: 'grid',
              gridTemplateColumns: `repeat(3, ${CELL_SIZE}px)`,
              gap: `${GRID_GAP}px`,
            }}
          >
            {procedural.map((entry) => (
              <PaperCell
                key={entry.id}
                entry={entry}
                active={entry.id === props.paperId}
                onSelect={props.onPaperIdChange}
                disabled={props.disabled}
              />
            ))}
          </div>
          <div
            class="paper-picker-group-header"
            data-paper-group-header="real"
            style={{
              position: 'sticky',
              top: 0,
              zIndex: 1,
              background: 'var(--color-bg-toolbar)',
              fontSize: '13px',
              fontWeight: 600,
              lineHeight: 1.2,
              color: 'var(--color-text-primary)',
              padding: '4px 0',
            }}
          >
            Real
          </div>
          <div
            class="paper-picker-grid"
            data-paper-group-grid="real"
            style={{
              display: 'grid',
              gridTemplateColumns: `repeat(3, ${CELL_SIZE}px)`,
              gap: `${GRID_GAP}px`,
            }}
          >
            {real.map((entry) => (
              <PaperCell
                key={entry.id}
                entry={entry}
                active={entry.id === props.paperId}
                onSelect={props.onPaperIdChange}
                disabled={props.disabled}
              />
            ))}
          </div>
        </div>
      {/* D-10: Strength + Scale sit directly under the grid, always
          reachable — never inside a popover (UI checklist row 10). */}
      <div class="paper-picker-sliders" data-paper-picker-sliders style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
        <SliderStepper
          id="paper-strength"
          label="Strength"
          value={props.strength}
          onChange={props.onStrengthChange}
          step={0.05}
          min={0}
          max={1}
          ariaLabel="Strength"
          disabled={props.disabled}
        />
        <SliderStepper
          id="paper-scale"
          label="Scale"
          value={props.scale}
          onChange={props.onScaleChange}
          step={0.1}
          min={0.1}
          max={10}
          ariaLabel="Scale"
          disabled={props.disabled}
        />
      </div>
    </div>
  );
}
