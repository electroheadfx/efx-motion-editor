import type { JSX } from 'preact';
import {
  PAPER_LIBRARY,
  PAPER_UNITS,
  type PaperDefinition,
} from '@efxlab/efx-watercolor/papers';
import { getEnginePaperSheet } from '../../../lib/enginePaperSheet';
import { SliderStepper } from '../../shared/SliderStepper';
import {
  GRAIN_SCALE_MAX,
  GRAIN_SCALE_MIN,
} from '../../../efx-paint/document/efxPaintDocument';
import type { StudioBackgroundMode } from '../engine/physicsPaintStudioSettings';

export interface PaperPickerProps {
  paperId: string;
  background: StudioBackgroundMode;
  grainStrength: number;
  grainScale: number;
  onPaperIdChange: (id: string) => void;
  onBackgroundChange: (mode: StudioBackgroundMode) => void;
  onGrainStrengthChange: (value: number) => void;
  onGrainScaleChange: (scale: number) => void;
  disabled?: boolean;
}

function paperName(paperId: string): string {
  return PAPER_LIBRARY.find((entry) => entry.id === paperId)?.name ?? paperId;
}

/** Cell size locked by UI-SPEC: 64×64 tiles, 8px grid gap. */
const CELL_SIZE = 64;
const GRID_GAP = 8;

/** Q6: Grain strength segmented values (None / Soft / Med / Hard). */
const GRAIN_STRENGTH_OPTIONS = [
  { label: 'None', value: 0 },
  { label: 'Soft', value: 0.35 },
  { label: 'Med', value: 0.65 },
  { label: 'Hard', value: 0.95 },
] as const;

/**
 * Locked Paper-background decision: Transparent + White are background, not
 * papers. They sit between the grain controls and the paper grid and reuse the
 * top-bar swatch look.
 */
const BACKGROUND_ARMS: { label: 'Transparent' | 'White'; value: 'transparent' | 'white'; swatch: string }[] = [
  { label: 'Transparent', value: 'transparent', swatch: 'repeating-conic-gradient(#777 0% 25%, #d8d8d8 0% 50%) 0 0 / 8px 8px' },
  { label: 'White', value: 'white', swatch: '#fff' },
];

/**
 * Grain scale step (UAT follow-up): 0.5 strictly inside ]0.5, 2.0[ — the default
 * 1.0 walks 1.5 ⇄ 0.5 in 0.5 jumps — and 0.1 at/below 0.5 and at/above 2.0
 * (0.5 − → 0.4, 2.0 + → 2.1). Pure so hold-to-repeat resolves it per emission.
 * 261017-vcn Q6: moved here with the grain widget from PhysicsPaintTopBar.
 */
export function grainScaleStep(value: number): number {
  return value > 0.5 && value < 2 ? 0.5 : 0.1;
}

function segmentedButtonClass(active: boolean) {
  return `physics-paint-segmented-button${active ? ' active' : ''}`;
}

/**
 * Nearest GRAIN_STRENGTH_OPTIONS match (261018-cy1). A non-finite or missing
 * strength resolves to Soft 0.35 — the factory default in
 * physicsPaintStudioSettings.ts (which must not change).
 */
function activeGrainOptionValue(grainStrength: number): number {
  const value = Number.isFinite(grainStrength) ? grainStrength : 0.35;
  let best = GRAIN_STRENGTH_OPTIONS[0].value;
  let bestDistance = Math.abs(value - best);
  for (const option of GRAIN_STRENGTH_OPTIONS) {
    const distance = Math.abs(value - option.value);
    if (distance < bestDistance) {
      best = option.value;
      bestDistance = distance;
    }
  }
  return best;
}

/**
 * Engine sheet preview (D-11): the same paperColour sheet the editor fond
 * shows, generated by the vendored WatercolorEngine (261017-nnu). Pure
 * presentation — no paperPass. Cached as canvas per (id, size) so re-renders
 * never regenerate. Painted into a cell <canvas> — never a toDataURL string
 * (52.1 D-19 forbids the frame-transport base64 surface, including picker
 * thumbs). Thumb scale: a ~256-paper-unit-tall window of the sheet so the
 * grain reads at a glance the way the playground preview does.
 */
const reliefCache = new Map<string, HTMLCanvasElement | null>();
const THUMB_WINDOW_UNITS = 256;
function proceduralReliefImage(id: string): HTMLCanvasElement | null {
  const key = `${id}:${CELL_SIZE}`;
  const cached = reliefCache.get(key);
  if (cached !== undefined) return cached;
  if (typeof document === 'undefined') {
    reliefCache.set(key, null);
    return null;
  }
  const sheet = getEnginePaperSheet(id, CELL_SIZE, CELL_SIZE, PAPER_UNITS / THUMB_WINDOW_UNITS);
  reliefCache.set(key, sheet);
  return sheet;
}

/**
 * 261017-mdr: pre-fill the procedural thumb cache so the picker opens without
 * a first-open generation stall. Same engine path proceduralReliefImage
 * already uses — repeat calls are reliefCache hits. Does not touch
 * CELL_SIZE / GRID_GAP / the 3-column grid.
 */
export function warmProceduralReliefThumbs(): void {
  for (const entry of PAPER_LIBRARY) {
    if (entry.group !== 'procedural') continue;
    proceduralReliefImage(entry.id);
  }
}

function PaperCell(props: {
  entry: PaperDefinition;
  active: boolean;
  onSelect: (id: string) => void;
  disabled?: boolean;
}): JSX.Element {
  const isReal = props.entry.group === 'real';
  const relief = isReal ? null : proceduralReliefImage(props.entry.id);
  // Loading / decode-failure share one placeholder: --color-bg-input + name
  // (UI-SPEC loading + error rows — never a blank cell, never a crash).
  const showPlaceholder = isReal || relief === null;
  return (
    <button
      type="button"
      class={`paper-picker-cell${props.active ? ' active' : ''}`}
      data-paper-id={props.entry.id}
      data-paper-group={props.entry.group}
      aria-pressed={props.active}
      title={props.entry.name}
      disabled={props.disabled}
      onClick={() => props.onSelect(props.entry.id)}
      style={{
        width: `${CELL_SIZE}px`,
        height: `${CELL_SIZE}px`,
        padding: 0,
        border: props.active ? '2px solid var(--color-accent)' : '1px solid var(--color-border-subtle)',
        borderRadius: '6px',
        overflow: 'hidden',
        cursor: props.disabled ? 'default' : 'pointer',
        background: 'var(--color-bg-input)',
        position: 'relative',
      }}
    >
      {showPlaceholder ? (
        isReal ? (
          <img
            src={props.entry.source}
            alt={props.entry.name}
            data-paper-tile="real"
            style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }}
            onError={(event) => {
              // Decode failure keeps the placeholder fill + name (UI-SPEC
              // error row) — hide the broken image, never a blank crash.
              (event.currentTarget as HTMLImageElement).style.display = 'none';
            }}
          />
        ) : null
      ) : (
        <canvas
          data-paper-tile="procedural"
          aria-label={props.entry.name}
          width={CELL_SIZE}
          height={CELL_SIZE}
          ref={(el: HTMLCanvasElement | null) => {
            if (!el) return;
            const ctx = el.getContext('2d');
            if (ctx && relief) ctx.drawImage(relief, 0, 0);
          }}
          style={{ width: '100%', height: '100%', display: 'block' }}
        />
      )}
      <span
        class="paper-picker-cell-name"
        style={{
          position: 'absolute',
          inset: 0,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          fontSize: '10px',
          fontWeight: 600,
          textAlign: 'center',
          padding: '2px',
          pointerEvents: 'none',
          // The name stays visible on the placeholder; over a decoded tile it
          // sits as a quiet caption strip so the raw tile still reads.
          background: showPlaceholder ? 'transparent' : 'linear-gradient(transparent 55%, rgba(0,0,0,0.45))',
          color: showPlaceholder ? 'var(--color-text-secondary)' : '#fff',
        }}
      >
        {props.entry.name}
      </span>
    </button>
  );
}

export function PaperPicker(props: PaperPickerProps): JSX.Element {
  const procedural = PAPER_LIBRARY.filter((entry) => entry.group === 'procedural');
  const real = PAPER_LIBRARY.filter((entry) => entry.group === 'real');
  const activeGrainValue = activeGrainOptionValue(props.grainStrength);

  return (
    <div class="paper-picker" data-paper-picker style={{ display: 'flex', flexDirection: 'column', gap: '8px' }}>
      {/* Q6: grain pair at the TOP of the Paper tab (former top-bar widgets). */}
      <div
        class="paper-picker-grain"
        data-paper-picker-grain
        style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}
      >
        <div class="physics-paint-segmented-row" role="group" aria-label="Grain strength">
          {GRAIN_STRENGTH_OPTIONS.map((option) => (
            <button
              key={option.label}
              type="button"
              disabled={props.disabled}
              class={segmentedButtonClass(activeGrainValue === option.value)}
              onClick={() => props.onGrainStrengthChange(option.value)}
            >
              {option.label}
            </button>
          ))}
        </div>
        <SliderStepper
          label="Grain scale"
          value={props.grainScale}
          step={grainScaleStep(props.grainScale)}
          resolveStep={grainScaleStep}
          min={GRAIN_SCALE_MIN}
          max={GRAIN_SCALE_MAX}
          ariaLabel="Grain scale"
          disabled={props.disabled}
          freeEntry
          onChange={props.onGrainScaleChange}
        />
      </div>

      {/* Locked Paper-background decision: Transparent + White arms (background,
          not papers) sit between the grain controls and the paper grid. */}
      <div
        class="physics-paint-segmented-row"
        role="group"
        aria-label="Background"
        data-paper-picker-backgrounds
      >
        {BACKGROUND_ARMS.map((option) => (
          <button
            key={option.value}
            type="button"
            disabled={props.disabled}
            class={`${segmentedButtonClass(props.background === option.value)} physics-paint-swatch-button`}
            title={option.label}
            aria-label={option.label}
            onClick={() => props.onBackgroundChange(option.value)}
          >
            <span class="physics-paint-paper-swatch" style={{ background: option.swatch }} />
          </button>
        ))}
      </div>

      {/* Flat grouping hook (261018-cy1): content sits in the tab body —
          no card chrome. Real papers come before Procedural. */}
      <div
        class="paper-picker-popover"
        data-paper-picker-popover
        style={{
          width: '100%',
          maxHeight: '320px',
          overflowY: 'auto',
          background: 'transparent',
          border: 'none',
          borderRadius: 0,
          padding: 0,
          display: 'flex',
          flexDirection: 'column',
          gap: '8px',
        }}
      >
          <div
            class="paper-picker-group-header"
            data-paper-group-header="real"
            style={{
              position: 'sticky',
              top: 0,
              zIndex: 1,
              background: 'var(--color-bg-toolbar)',
              fontSize: '13px',
              fontWeight: 600,
              lineHeight: 1.2,
              color: 'var(--color-text-primary)',
              padding: '4px 0',
            }}
          >
            Real
          </div>
          <div
            class="paper-picker-grid"
            data-paper-group-grid="real"
            style={{
              display: 'grid',
              gridTemplateColumns: `repeat(3, ${CELL_SIZE}px)`,
              gap: `${GRID_GAP}px`,
            }}
          >
            {real.map((entry) => (
              <PaperCell
                key={entry.id}
                entry={entry}
                active={entry.id === props.paperId}
                onSelect={props.onPaperIdChange}
                disabled={props.disabled}
              />
            ))}
          </div>
          <div
            class="paper-picker-group-header"
            data-paper-group-header="procedural"
            style={{
              position: 'sticky',
              top: 0,
              zIndex: 1,
              background: 'var(--color-bg-toolbar)',
              fontSize: '13px',
              fontWeight: 600,
              lineHeight: 1.2,
              color: 'var(--color-text-primary)',
              padding: '4px 0',
            }}
          >
            Procedural
          </div>
          <div
            class="paper-picker-grid"
            data-paper-group-grid="procedural"
            style={{
              display: 'grid',
              gridTemplateColumns: `repeat(3, ${CELL_SIZE}px)`,
              gap: `${GRID_GAP}px`,
            }}
          >
            {procedural.map((entry) => (
              <PaperCell
                key={entry.id}
                entry={entry}
                active={entry.id === props.paperId}
                onSelect={props.onPaperIdChange}
                disabled={props.disabled}
              />
            ))}
          </div>
        </div>
    </div>
  );
}
